#!/bin/sh
# Generate the 256 interrupt stubs and their address table (isrs_gen.S).
#
# Each stub pushes a dummy error code — unless the CPU pushes a real one for
# that vector (error-code vectors per Intel SDM Vol. 3A: 8, 10-14, 17, 21,
# 29, 30) — plus the vector number, forming one uniform frame for
# isr_common, then jumps there. The trailing table (isr_stub_table) lets the
# C++ side fill the IDT without 256 hand-written extern declarations.
#
# usage: gen_isrs.sh <output.S>
out=$1

# Vectors whose stubs must NOT push a dummy error code.
err_vecs="8 10 11 12 13 14 17 21 29 30"

is_err() {
    for v in $err_vecs; do
        [ "$v" = "$1" ] && return 0
    done
    return 1
}

{
    echo '/* generated by gen_isrs.sh - do not edit */'
    echo '.text'
    i=0
    while [ "$i" -lt 256 ]; do
        echo ".p2align 2"
        echo ".global isr_$i"
        echo "isr_$i:"
        if ! is_err "$i"; then
            echo "    pushq \$0          /* dummy error code: uniform frame */"
        fi
        echo "    pushq \$$i         /* vector number */"
        echo "    jmp isr_common"
        i=$((i + 1))
    done
    echo '.p2align 3'
    echo '.global isr_stub_table'
    echo 'isr_stub_table:'
    i=0
    while [ "$i" -lt 256 ]; do
        echo "    .quad isr_$i"
        i=$((i + 1))
    done
} > "$out"
